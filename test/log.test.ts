import "./isolate.js";
import assert from "node:assert/strict";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, test } from "node:test";
import type { Config } from "../src/config.js";
import { addEntry, exportView, importFile, listEntries, parseImport, renderView } from "../src/log.js";
import { Store } from "../src/store.js";

let root: string;
let vault: string;
const cfg = (machine = "mini", exports: Config["exports"] = []): Config => ({
  logDir: "log",
  machine,
  exports,
  userConfigPath: "",
});

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), "brain-log-"));
  vault = join(root, "vault");
  mkdirSync(vault);
});
afterEach(() => rmSync(root, { recursive: true, force: true }));

test("addEntry writes a new file with kind, created, machine, tags and an H1 title", () => {
  const path = addEntry(vault, cfg(), {
    kind: "Learning",
    title: "pnpm cache breaks\n after updates",
    body: "Run pnpm store prune.",
    tags: ["#Ops", "ops"],
    created: new Date("2026-10-13T02:00:00.123Z"),
  });
  assert.equal(path, "log/learning/2026-10-13-mini-pnpm-cache-breaks-after-updates.md");
  assert.equal(
    readFileSync(join(vault, path), "utf8"),
    "---\nkind: learning\ncreated: 2026-10-13T02:00:00.123Z\nmachine: mini\ntags: [ops]\n---\n# pnpm cache breaks after updates\n\nRun pnpm store prune.\n",
  );
});

test("addEntry never overwrites: a same-day duplicate title gets a suffix", () => {
  const a = addEntry(vault, cfg(), { kind: "learning", title: "Same" });
  const b = addEntry(vault, cfg(), { kind: "learning", title: "Same" });
  assert.notEqual(a, b);
  assert.match(b, /-same-2\.md$/);
  assert.equal(readdirSync(join(vault, "log/learning")).length, 2);
});

test("listEntries reads entries back newest first, filtered by kind", () => {
  addEntry(vault, cfg(), { kind: "learning", title: "Old", created: new Date("2026-01-01T00:00:00Z") });
  addEntry(vault, cfg("laptop"), { kind: "learning", title: "New", body: "Body text", created: new Date("2026-02-01T00:00:00Z") });
  addEntry(vault, cfg(), { kind: "decision", title: "Other kind" });
  mkdirSync(join(vault, "notes"));
  writeFileSync(join(vault, "notes/x.md"), "---\nkind: learning\n---\n# Not in the log folder\n");
  const store = Store.open(vault);
  store.refresh();
  const entries = listEntries(store, cfg(), { kind: "learning" });
  assert.deepEqual(entries.map((e) => [e.title, e.machine, e.body]), [
    ["New", "laptop", "Body text"],
    ["Old", "mini", ""],
  ]);
  assert.equal(listEntries(store, cfg()).length, 3);
  store.close();
});

test("parseImport: one entry per top-level bullet, continuations kept, markers stripped, headings become tags", () => {
  const items = parseImport(
    [
      "<!-- memory tiers: see the stow skill -->",
      "- Staging needs the VPN profile. <!--a:2026-08-03-->",
      "- Always lint the schema. <!--P-->",
      "  It catches drift before migrations.",
      "",
      "## Deploys",
      "1. Vercel builds from main.",
      "A loose paragraph line.",
    ].join("\n"),
  );
  assert.deepEqual(items, [
    { title: "Staging needs the VPN profile.", body: "", tags: [] },
    { title: "Always lint the schema.", body: "It catches drift before migrations.", tags: [] },
    { title: "Vercel builds from main.", body: "", tags: ["deploys"] },
    { title: "A loose paragraph line.", body: "", tags: ["deploys"] },
  ]);
});

test("renderView is oldest first and shows a duplicate text once", () => {
  const base = { kind: "learning", machine: "", tags: [] as string[], body: "" };
  const md = renderView(
    [
      { ...base, path: "b", title: "Second", created: "2026-01-02T00:00:00.000Z" },
      { ...base, path: "a", title: "First", created: "2026-01-01T00:00:00.000Z" },
      { ...base, path: "c", title: "first ", created: "2026-01-03T00:00:00.000Z" },
    ],
    "<!-- header -->",
  );
  assert.equal(
    md,
    '<!-- header -->\n<!-- generated by brain from 2 learning entries; add one with: brain log add learning "<text>" -->\n- First\n- Second\n',
  );
});

test("import then export: lossless round trip, then drift protection", () => {
  const target = join(root, "fm/data/learnings.md");
  mkdirSync(join(root, "fm/data"), { recursive: true });
  writeFileSync(target, "- One\n- Two\n");
  const c = cfg("mini", [{ kind: "learning", path: target }]);
  const store = Store.open(vault);
  store.refresh();

  // An existing file brain never wrote is not overwritten.
  assert.equal(exportView(store, c, c.exports[0]!).status, "drift");
  assert.equal(readFileSync(target, "utf8"), "- One\n- Two\n");

  const result = importFile(store, c, "learning", target);
  assert.equal(result.added.length, 2);
  store.refresh();
  assert.equal(importFile(store, c, "learning", target).skipped, 2, "re-import skips recorded titles");
  store.refresh();

  // Captured, so the export may now replace it — and keeps the order.
  assert.equal(exportView(store, c, c.exports[0]!).status, "written");
  assert.match(readFileSync(target, "utf8"), /- One\n- Two\n$/);
  assert.equal(exportView(store, c, c.exports[0]!).status, "unchanged");

  // Someone (stow) edits the exported file: the next export refuses.
  writeFileSync(target, readFileSync(target, "utf8") + "- Three, by hand\n");
  assert.equal(exportView(store, c, c.exports[0]!).status, "drift");
  assert.match(readFileSync(target, "utf8"), /Three, by hand/);
  // --force is the explicit override.
  assert.equal(exportView(store, c, c.exports[0]!, true).status, "written");
  assert.doesNotMatch(readFileSync(target, "utf8"), /Three/);
  assert.ok(!existsSync(`${target}.brain-tmp-${process.pid}`));
  store.close();
});
